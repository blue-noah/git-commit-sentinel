// Package hookfile renders the small POSIX shell script installed as the
// git commit-msg hook, and detects whether an existing file at that
// location was put there by git-commit-sentinel.
package hookfile

import (
	"fmt"
	"strings"
)

// Marker identifies a hook file as managed by git-commit-sentinel. Its
// presence lets `setup` overwrite its own previous installs without
// clobbering a hook the user wrote by hand.
const Marker = "# managed-by: git-commit-sentinel"

// BinaryName is the executable's name, which the hook looks up on PATH
// when the binary it was rendered with is gone.
const BinaryName = "git-commit-sentinel"

// Render returns the commit-msg hook script content. The hook runs the
// binary at binPath, so it works for git clients whose PATH lacks the
// install directory (e.g. GUI apps on macOS), and falls back to
// BinaryName on PATH when binPath no longer exists.
func Render(binPath string) string {
	return fmt.Sprintf(
		"#!/bin/sh\n%s\n# Do not edit by hand: re-run `%s setup` to regenerate.\nbin=%s\n[ -x \"$bin\" ] || bin=%s\nexec \"$bin\" hook \"$1\"\n",
		Marker, BinaryName, shellQuote(binPath), BinaryName,
	)
}

// shellQuote quotes s as a single POSIX shell word.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// IsManaged reports whether content was generated by Render (in this or an
// earlier version), identified by the marker comment.
func IsManaged(content string) bool {
	return strings.Contains(content, Marker)
}
